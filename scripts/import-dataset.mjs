// Regenerates src/lib/data/catalog.generated.ts from the published dataset
// "Industrial Storage Container Dimensions" by Daniel Rosehill (CC BY 4.0):
// https://huggingface.co/datasets/danielrosehill/storage-container-dimensions
//
// Usage: node scripts/import-dataset.mjs [path/to/containers.csv]
// Without an argument the CSV is downloaded from Hugging Face.

import { readFile, writeFile } from 'node:fs/promises';

const DATASET_URL =
  'https://huggingface.co/datasets/danielrosehill/storage-container-dimensions/resolve/main/containers.csv';
const OUT = new URL('../src/lib/data/catalog.generated.ts', import.meta.url);

const FAMILY = {
  euro_stacking_container: 'euro',
  attached_lid_container: 'alc',
  vda_klt_container: 'klt',
};

/** Minimal RFC 4180 CSV parser (quoted fields, embedded commas/newlines). */
function parseCsv(text) {
  const rows = [];
  let row = [];
  let field = '';
  let quoted = false;
  for (let i = 0; i < text.length; i++) {
    const c = text[i];
    if (quoted) {
      if (c === '"' && text[i + 1] === '"') { field += '"'; i++; }
      else if (c === '"') quoted = false;
      else field += c;
    } else if (c === '"') quoted = true;
    else if (c === ',') { row.push(field); field = ''; }
    else if (c === '\n' || c === '\r') {
      if (c === '\r' && text[i + 1] === '\n') i++;
      row.push(field); rows.push(row); row = []; field = '';
    } else field += c;
  }
  if (field || row.length) { row.push(field); rows.push(row); }
  const [header, ...body] = rows.filter((r) => r.length > 1);
  return body.map((r) => Object.fromEntries(header.map((h, i) => [h, r[i] ?? ''])));
}

const num = (v) => (v === '' || v == null ? null : Number(v));
const mm = (cm) => (cm == null ? null : Math.round(cm * 10));

const source = process.argv[2]
  ? await readFile(process.argv[2], 'utf8')
  : await (await fetch(DATASET_URL)).text();

const boxes = parseCsv(source)
  .filter((r) => FAMILY[r.type])
  .map((r) => ({
    id: r.id,
    family: FAMILY[r.type],
    length: mm(num(r.external_length_cm)),
    width: mm(num(r.external_width_cm)),
    height: mm(num(r.external_height_cm)),
    capacityL: num(r.typical_capacity_l),
    capacityLowL: num(r.vendor_capacity_low_l),
    capacityHighL: num(r.vendor_capacity_high_l),
    lidded: r.lidded === 'True',
  }));

const out = `// GENERATED by scripts/import-dataset.mjs — do not edit by hand.
// Source: "Industrial Storage Container Dimensions" by Daniel Rosehill, CC BY 4.0
// https://huggingface.co/datasets/danielrosehill/storage-container-dimensions
// External dimensions in mm, capacities in litres.
import type { BoxType } from '../model/types';

export const DATASET_BOXES: BoxType[] = ${JSON.stringify(boxes, null, 2)};
`;

await writeFile(OUT, out);
console.log(`Wrote ${boxes.length} boxes to ${OUT.pathname}`);
